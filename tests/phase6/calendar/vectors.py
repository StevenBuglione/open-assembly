"""Produce Gregorian UTC fixtures from civil labels and the Unix epoch."""

from datetime import date

DATES = (
    (1969, 12, 30, 23, 59, 59), (1969, 12, 31, 0, 0, 0),
    (1969, 12, 31, 23, 59, 59), (1970, 1, 1, 0, 0, 0), (1970, 1, 1, 0, 0, 1),
    (1600, 2, 29, 12, 34, 56), (1700, 3, 1, 0, 0, 0), (1900, 2, 28, 23, 59, 59),
    (1900, 3, 1, 0, 0, 0), (1904, 2, 29, 0, 0, 0), (2000, 2, 29, 23, 59, 59),
    (2000, 3, 1, 0, 0, 0), (2100, 3, 1, 0, 0, 0), (2400, 2, 29, 0, 0, 0),
    (2038, 1, 19, 3, 14, 7), (2038, 1, 19, 3, 14, 8),
    (1901, 12, 13, 20, 45, 52), (1901, 12, 13, 20, 45, 51),
    (1, 1, 1, 0, 0, 0), (0, 2, 29, 7, 8, 9), (-400, 2, 29, 5, 6, 7),
    (-100, 3, 1, 0, 0, 0), (10000, 12, 31, 23, 59, 59),
    (1900 - 2 ** 31, 1, 1, 0, 0, 0), (1900 - 2 ** 31, 12, 31, 23, 59, 59),
    (1899 + 2 ** 31, 1, 1, 0, 0, 0), (1899 + 2 ** 31, 12, 31, 23, 59, 59),
)
OUTSIDE = ((1899 - 2 ** 31, 12, 31, 23, 59, 59), (1900 + 2 ** 31, 1, 1, 0, 0, 0))


def leap(year):
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def january_first(year):
    leap_days = (year + 3) // 4 - (year + 99) // 100 + (year + 399) // 400
    return 365 * year + leap_days


def fields(row):
    year, month, day, hour, minute, second = row
    months = (31, 28 + leap(year), 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)
    year_day = sum(months[:month - 1]) + day - 1
    days = january_first(year) + year_day - january_first(1970)
    week_day = (days + 4) % 7
    if 1 <= year <= 9999:
        current = date(year, month, day)
        assert days == (current - date(1970, 1, 1)).days
        assert week_day == (current.weekday() + 1) % 7
    stamp = days * 86400 + hour * 3600 + minute * 60 + second
    return stamp, (second, minute, hour, day, month - 1, year - 1900, week_day, year_day)


def main():
    print("/* Generated by vectors.py. */")
    print("static const struct civil_case cases[] = {")
    for row in DATES:
        stamp, values = fields(row)
        print(f"    {{ {stamp}L, {{ {', '.join(map(str, values))} }} }},")
    print("};")
    print("static const time_t overflow[] = {")
    for row in OUTSIDE:
        print(f"    {fields(row)[0]}L,")
    print("    (-9223372036854775807L - 1), 9223372036854775807L,")
    print("};")


if __name__ == "__main__":
    main()
